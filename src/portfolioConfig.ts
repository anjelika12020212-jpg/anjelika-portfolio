/**
 * Единый конфигурационный файл портфолио.
 * Здесь можно изменить имя, контакты, ссылки и параметры проектов.
 */

export interface ScenarioGroup {
  roleTitle: string;
  steps: string[];
}

export interface ProjectDetails {
  /** Какую задачу решает */
  problem: string;
  /** Заголовок раздела решения (по умолчанию 'Предлагаемое решение') */
  solutionTitle?: string;
  /** Предлагаемое решение */
  solution: string;
  /** Заголовок третьего раздела (по умолчанию 'Как устроен основной сценарий пользователя') */
  scenarioTitle?: string;
  /** Как устроен основной сценарий пользователя (шаги) */
  userScenario?: string[];
  /** Сценарии, разделенные по ролям (например: Для спортсмена / Для тренера) */
  scenarioGroups?: ScenarioGroup[];
}

export interface ProjectItem {
  id: string;
  number: string;
  category: string;
  title: string;
  subtitle: string;
  description: string;
  accentColor: string;
  /** Статус проекта (например, 'В разработке', 'MVP', 'Концепт') */
  status?: string;
  /**
   * Ссылка на рабочий проект.
   * Если строка пустая или не указана, кнопка перехода скрывается.
   */
  link?: string;
  details: ProjectDetails;
}

export interface PortfolioConfig {
  author: {
    name: string;
    fullName: string;
    role: string;
  };
  navigation: {
    projects: string;
    about: string;
    contacts: string;
  };
  hero: {
    badge: string;
    titleLine1: string;
    titleLine2: string;
    description: string;
    primaryCta: string;
    secondaryCta: string;
  };
  projects: ProjectItem[];
  about: {
    title: string;
    description: string;
  };
  contacts: {
    title: string;
    description: string;
    /**
     * Ссылка на Telegram (например, 'https://t.me/username').
     */
    telegram: string;
    /**
     * Email (например, 'contact@example.com').
     */
    email: string;
    /**
     * Телефон в отображаемом формате (например, '+7 916-114-46-68').
     */
    phone: string;
  };
}

